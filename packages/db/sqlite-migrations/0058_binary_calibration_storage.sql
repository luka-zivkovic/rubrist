CREATE TRIGGER binary_calibration_run_insert BEFORE INSERT ON binary_calibration_runs BEGIN
 SELECT CASE WHEN NEW.created_at IS NOT sqlite_command_time() OR NEW.state<>'queued' OR NEW.accounted_observations<>0 OR NEW.planned_observations<>NEW.item_count OR NEW.claim_token IS NOT NULL OR NEW.authorization_check_id IS NOT NULL OR NEW.completion_check_id IS NOT NULL OR NEW.artifact_id IS NOT NULL OR NEW.artifact_digest IS NOT NULL OR NEW.evidence_digest IS NOT NULL OR NEW.rejection_reason IS NOT NULL OR NEW.started_at IS NOT NULL OR NEW.completed_at IS NOT NULL THEN RAISE(ABORT,'calibration creation requires fresh queued command') END;
 SELECT CASE WHEN NEW.provider_policy_digest IS NOT governed_bytes_v1_digest(NEW.provider_policy_canonical_bytes) THEN RAISE(ABORT,'calibration provider policy byte digest mismatch') END;
 SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM dataset_revisions r JOIN skill_versions v ON v.id=NEW.skill_version_id AND v.project_id=r.project_id JOIN skills s ON s.id=v.skill_id AND s.project_id=v.project_id JOIN criterion_versions cv ON cv.id=v.criterion_version_id AND cv.project_id=v.project_id
 WHERE r.id=NEW.dataset_revision_id AND r.project_id=NEW.project_id AND r.role='sealed_validation' AND r.source_kind='sealed_intake' AND r.provenance_level='governed_blind' AND r.revision_digest=NEW.revision_digest AND r.content_digest=NEW.truth_content_digest AND r.item_count=NEW.item_count
 AND v.skill_id=NEW.skill_id AND v.criterion_version_id=NEW.criterion_version_id AND governed_canonical_json_v1(v.execution_binding)=governed_canonical_json_v1(NEW.execution_binding) AND s.criterion_id=NEW.criterion_id AND cv.criterion_id=NEW.criterion_id AND cv.criterion_digest=NEW.criterion_digest)
 THEN RAISE(ABORT,'calibration requires exact governed sealed evaluator lineage') END;
 SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM governed_review_batches b JOIN review_instruction_versions i ON i.id=b.instruction_version_id JOIN governed_review_batch_events f ON f.batch_id=b.id AND f.event_kind='frozen' WHERE b.id=NEW.governed_review_batch_id AND b.project_id=NEW.project_id AND b.criterion_version_id=NEW.criterion_version_id AND b.content_digest=NEW.governed_review_batch_digest AND b.instruction_version_id=NEW.review_instruction_version_id AND i.content_digest=NEW.review_instruction_digest AND f.dataset_revision_id=NEW.dataset_revision_id AND b.population_id=NEW.population_id AND b.population_digest=NEW.population_digest AND b.draw_digest=NEW.draw_digest AND b.selection_method=NEW.selection_method) THEN RAISE(ABORT,'calibration requires exact frozen batch origin') END;
 SELECT CASE WHEN NEW.suite_manifest_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM evaluator_suite_manifests m JOIN json_each(CAST(m.canonical_bytes AS TEXT),'$.members') x ON x.key=NEW.suite_member_position WHERE m.id=NEW.suite_manifest_id AND m.project_id=NEW.project_id AND m.manifest_digest=NEW.suite_manifest_digest AND json_type(CAST(m.canonical_bytes AS TEXT),'$.trialPlan')='null' AND json_extract(x.value,'$.skillVersionId')=NEW.skill_version_id AND json_extract(x.value,'$.criterionVersionId')=NEW.criterion_version_id AND json_extract(x.value,'$.skillDigest')=NEW.skill_digest AND json_extract(x.value,'$.outputContractDigest')=NEW.output_contract_digest) THEN RAISE(ABORT,'calibration requires exact single-trial suite member') END;
END;
